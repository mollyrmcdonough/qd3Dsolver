"""Emit every material parameter in a form that can be checked line by line against a source.

Written because the InAs/InSb parameter set failed its first benchmark (Pryor & Pistol 2005) and
the failure localized to the hydrostatic deformation potentials -- see
`scripts/insb_pryor_pistol_check.py` and the README. The point of this script is to put the whole
set, including the derived quantities and the sign conventions, in one auditable place rather
than have someone re-transcribe it by hand.

Everything here is READ FROM `materials.py`, not retyped, so the document cannot drift from the
code. Run:  python scripts/dump_sb_parameters.py > SB_PARAMETERS.md
"""
