P = print


def row(name, fmt='{:.4f}', note=''):
    P(f"| `{name}` |" + '|'.join(f" {fmt.format(mt.MATERIALS[m][name])} " for m in MATS)
      + f"| {mt.PROVENANCE.get(name, '')} | {note} |")


